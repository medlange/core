def iter_target_files(root: Path) -> Iterator[Path]:
    for p in sorted(root.rglob("*")):
        if not p.is_file():
            continue
        if SKIP_PATH_PARTS.intersection(p.parts):
            continue
        if p.name.startswith(SKIP_NAME_PREFIXES):
            continue
        suffix = p.suffix.lower()
        if suffix in (".mrml", ".nrrd"):
            yield p


def file_kind(p: Path) -> str:
    if p.suffix.lower() == ".mrml":
        return "mrml"
    if p.name.lower().endswith(".seg.nrrd"):
        return "seg.nrrd"
    return "nrrd"


def path_component_categories(comp: str, scrubber: Scrubber) -> list[str]:
    """Classify one path component.

    Shared by the "not rewritten" inventory and by report-path redaction so the
    two can never disagree - a component reported as carrying an identifier must
    also be the one that gets redacted out of the report text.
    """
    cats: list[str] = []
    if RE_SITE_TOKEN.search(comp):
        cats.append(CAT_SITE_TOKEN)
    if RE_PSEUDONYM.search(comp):
        cats.append(CAT_PSEUDONYM)
    if RE_CYRILLIC_RUN.search(comp):
        cats.append(CAT_CYRILLIC_TEXT)
    if RE_UNNAMED.search(comp):
        cats.append(CAT_ACCESSION)
    if RE_USER_HOME.search("/" + comp + "/"):
        cats.append(CAT_LOCAL_USER_PATH)
    # A Study/Series/SOP Instance UID is a direct identifier under Safe Harbor
    # ("any other unique identifying number"), so a filename that is a UID must
    # not be echoed into the report either.
    stem = comp[: -len(Path(comp).suffix)] if Path(comp).suffix else comp
    if any(is_dicom_uid(m.group(1)) for m in RE_UID.finditer(comp)) or is_dicom_uid(stem):
        cats.append(CAT_DICOM_UID)
    for _core, cat, _rank in scrubber._identity_cores(comp):
        cats.append(cat)
    return sorted(set(cats))


def scan_path_identifiers(
    targets: Sequence[tuple[Path, Path]], paths: "RunPaths", scrubber: Scrubber
) -> list[dict[str, Any]]:
    """Report identifiers that live in file and directory *names*.

    These are NOT rewritten: a Slicer scene's `fileName` attributes and a
    multi-file NRRD's `data file` field point at these names, and renaming them
    from here would silently break every scene that references them.  The
    operator needs to know they exist, so they are reported and excluded from the
    --verify assertion rather than quietly ignored.
    """
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    for root, p in targets:
        for comp in p.relative_to(root).parts:
            if comp in seen:
                continue
            cats = path_component_categories(comp, scrubber)
            if cats:
                seen.add(comp)
                out.append(
                    {
                        "root": paths.root_labels[root],
                        "component_phi_ref": scrubber.phi_ref(comp),
                        "categories": cats,
                    }
                )
    return out


def redact_rel_path(rel: str, scrubber: Scrubber) -> str:
    """Keep the path actionable but strip PHI-bearing components.

    Directory names in these corpora sometimes carry an institution name in
    Cyrillic; a report that quotes them is a report that leaks.
    """
    parts = []
    for comp in Path(rel).parts:
        cats = path_component_categories(comp, scrubber)
        if cats:
            parts.append(f"<redacted:{','.join(cats)}:{scrubber.phi_ref(comp)}>")
        else:
            parts.append(comp)
    return "/".join(parts)


