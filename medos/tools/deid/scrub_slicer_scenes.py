"""Scrub PHI out of 3D Slicer sidecar files (.mrml scenes, .nrrd headers).

WHY THIS TOOL EXISTS
--------------------
The NRRD *volumes* in the PulmoAI corpora are clean: the leak is entirely in the
Slicer sidecars.  A `.mrml` scene is a full XML dump of the Slicer subject
hierarchy, so it carries the DICOM attributes Slicer imported - patient name,
patient ID, birth date, study date - plus every filesystem path the annotator's
laptop happened to use.  A `.seg.nrrd` header carries `SegmentN_ID`, which Slicer
derives from the source model name and which therefore inherits the same string.

WHY PSEUDONYMISE RATHER THAN DELETE
-----------------------------------
Deleting `uids=` breaks the scene: Slicer uses those UIDs to bind a loaded volume
back to its DICOM series, and a segmentation whose referenced series UID is gone
loads as an orphan.  More importantly, spec chapter 03 (`docs/spec/03-medical-data-plane.md`)
makes consistent remapping a *blocking invariant*:

  MOS-DATA-031  UID remapping MUST be deterministic, consistent and reversible
                within a tenant.  For a fixed (tenant_id, deid_key_version) the
                same source UID MUST map to the same de-identified UID forever,
                across processes, restarts and re-ingests, and two distinct
                source UIDs MUST NEVER map to the same de-identified UID.
                Per-invocation or per-export random remapping is forbidden.
  MOS-DATA-032  The de-identified UID MUST be generated by
                `2.25.<int(uuid_from_hmac_sha256(tenant_deid_key, source_uid))>`.
  MOS-DATA-033  The mapping table is authoritative; MOS-DATA-032 is the generator
                that allows it to be rebuilt.  A generated UID that collides with
                an existing row for a *different* source UID MUST abort.
  MOS-DATA-034  A UID under the `1.2.840.10008` DICOM-registered root MUST be
                copied unchanged; every other UID MUST be remapped.
  MOS-DATA-037  De-identification MUST fail closed - never emit a partially
                de-identified object.

Concretely: a `ResultBundle` references source SOP Instance UIDs, and a
`DatasetVersion` is a content-addressed manifest of SOP Instance UIDs.  If this
script remapped per-file or per-run, every segmentation in the corpus would point
at UIDs that no longer exist and every dataset manifest hash would change on every
export.  Nothing would raise; the failure surfaces months later as an overlay that
does not line up.  Hence one process-wide, key-derived, collision-checked map.

WHY THE REPORT CONTAINS NO PHI
------------------------------
A de-identification report that quotes what it removed is itself a PHI disclosure,
and reports get mailed around.  Every removed value is referenced only by
`phi_ref`, a salted HMAC prefix, so two findings can be correlated without the
report carrying the value.  Path components that themselves contain PHI markers
are redacted the same way.

DEPENDENCIES
------------
numpy and pynrrd only (see requirements.txt next to this file).  pynrrd is used
solely to *verify* a rewritten NRRD header round-trips - the rewrite itself is
done on raw bytes so pixel data is never decoded, re-encoded, or touched.

SAFETY
------
Dry run by default.  `--apply` is required to write, every write is preceded by a
copy into `--backup-dir`, and the run aborts before touching anything if any
backup target already exists.

That last refusal is also the re-application guard.  UID remapping and surrogate
allocation are idempotent (the map is reloaded, our own tokens are recognised),
but `--date-policy shift` is not: a shifted date is shaped exactly like a real
one, so applying twice would shift twice.  Refusing to reuse a backup directory
is what makes that impossible.  Use `--date-policy redact` if you need a
transform that is safe to re-run.
"""

