def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="scrub_slicer_scenes",
        description=(
            "De-identify 3D Slicer .mrml scenes and .nrrd headers in place. "
            "Dry run by default; --apply is required to write. UIDs are pseudonymised "
            "deterministically (spec MOS-DATA-031/032), never deleted."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "examples:\n"
            "  # survey, write nothing\n"
            "  python scrub_slicer_scenes.py\n"
            "  # survey one tree\n"
            "  python scrub_slicer_scenes.py --root /data/pneumonia\n"
            "  # write, backing every original up first\n"
            "  python scrub_slicer_scenes.py --apply --backup-dir /secure/backup\n"
            "  # prove nothing is left\n"
            "  python scrub_slicer_scenes.py --verify\n"
        ),
    )
    p.add_argument("--root", action="append", metavar="DIR",
                   help="dataset root to scan (repeatable). Default: DEFAULTS['roots'].")
    p.add_argument("--work-dir", default=DEFAULTS["work_dir"], metavar="DIR",
                   help="base directory for key, map, backups and report (default: %(default)s)")
    p.add_argument("--backup-dir", metavar="DIR", help="where originals are copied before --apply")
    p.add_argument("--key-file", metavar="FILE",
                   help="hex secret used for UID and surrogate derivation; generated if absent")
    p.add_argument("--map-out", metavar="FILE", help="UID mapping table (JSON Lines)")
    p.add_argument("--report", metavar="FILE", help="machine-readable JSON report")
    p.add_argument("--apply", action="store_true", help="actually write (default is a dry run)")
    p.add_argument("--verify", action="store_true",
                   help="re-scan and exit non-zero if any residual PHI match remains")
    p.add_argument("--date-policy", choices=("shift", "redact", "keep"), default="shift",
                   help="what to do with DICOM dates (default: %(default)s; shift keeps intervals exact)")
    p.add_argument("--cyrillic-policy", choices=("redact", "path-only", "keep"), default="redact",
                   help="Cyrillic runs: redact everywhere, only inside paths, or keep (default: %(default)s)")
    p.add_argument("--mrn-min-digits", type=int, default=DEFAULTS["mrn_min_digits"], metavar="N",
                   help="shortest standalone digit run treated as a record number (default: %(default)s)")
    p.add_argument("--link-scope", choices=("file", "element"), default="file",
                   help=("whether identities found in one scene are assumed to be one case "
                         "(default: %(default)s). Use 'element' for multi-patient scenes."))
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.apply and args.verify:
        print("--apply and --verify are mutually exclusive.", file=sys.stderr)
        return 64
    try:
        return run(args)
    except ScrubError as exc:
        print(f"\nERROR: {exc}\n", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
