@dataclass
class RunPaths:
    roots: list[Path]
    root_labels: dict[Path, str]
    backup_dir: Path
    key_file: Path
    map_out: Path
    report_out: Path


def _is_within(child: Path, parent: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def resolve_paths(args: argparse.Namespace) -> RunPaths:
    roots = [Path(r).resolve() for r in (args.root or DEFAULTS["roots"])]
    for r in roots:
        if not r.is_dir():
            raise ScrubError(f"--root {r} is not a directory")

    work = Path(args.work_dir).resolve()
    backup_dir = Path(args.backup_dir).resolve() if args.backup_dir else (work / DEFAULTS["backup_subdir"])
    key_file = Path(args.key_file).resolve() if args.key_file else (work / DEFAULTS["key_name"])
    map_out = Path(args.map_out).resolve() if args.map_out else (work / DEFAULTS["map_name"])
    report_out = Path(args.report).resolve() if args.report else (work / DEFAULTS["report_name"])

    # The map and the key ARE the re-identification capability. Inside the dataset
    # tree they would travel with the data and undo the entire exercise.
    for label, p in (("--backup-dir", backup_dir), ("--key-file", key_file), ("--map-out", map_out),
                     ("--report", report_out)):
        for r in roots:
            if _is_within(p, r):
                raise ScrubError(
                    f"{label} ({p}) is inside the dataset root {r}. "
                    "Backups, keys, UID maps and reports must live outside the data they describe."
                )

    labels: dict[Path, str] = {}
    used: set[str] = set()
    for r in roots:
        base = re.sub(r"[^A-Za-z0-9_.-]+", "_", r.name) or "root"
        label, n = base, 1
        while label in used:
            n += 1
            label = f"{base}_{n}"
        used.add(label)
        labels[r] = label
    return RunPaths(roots, labels, backup_dir, key_file, map_out, report_out)


def run(args: argparse.Namespace) -> int:
    paths = resolve_paths(args)
    mode = "verify" if args.verify else ("apply" if args.apply else "dry-run")

    key = load_or_create_key(paths.key_file, allow_create=not args.verify)
    report_salt = hmac.new(key, b"medicalos/deid/report-salt", hashlib.sha256).digest()

    policy = Policy(
        mrn_min_digits=args.mrn_min_digits,
        mrn_max_digits=DEFAULTS["mrn_max_digits"],
        date_mode=args.date_policy,
        date_shift_window=DEFAULTS["date_shift_window_days"],
        cyrillic_mode=args.cyrillic_policy,
        date_min_year=DEFAULTS["date_min_year"],
        date_max_year=DEFAULTS["date_max_year"],
    )
    uid_mapper = UidMapper(key)
    uid_mapper.load_existing(paths.map_out)
    surrogates = SurrogateRegistry(key)
    scrubber = Scrubber(uid_mapper=uid_mapper, surrogates=surrogates, policy=policy, report_salt=report_salt)

    targets: list[tuple[Path, Path]] = []
    for root in paths.roots:
        for p in iter_target_files(root):
            targets.append((root, p))
    if not targets:
        raise ScrubError(f"no .mrml or .nrrd files found under {', '.join(str(r) for r in paths.roots)}")

    # -- pass 1: discovery -------------------------------------------------- #
    scrubber.discover = True
    scrubber.link_scope = args.link_scope
    for root, p in targets:
        scrubber.begin_file(str(p), _fallback_core(root, p))
        throwaway = FileResult(p, paths.root_labels[root], "", file_kind(p))
        try:
            _dispatch(p, scrubber, throwaway)
        except ScrubError:
            raise
        except Exception as exc:  # noqa: BLE001 - re-raised with the file name attached
            raise ScrubError(f"{p}: discovery pass failed: {type(exc).__name__}: {exc}") from exc
        scrubber.end_file()
    surrogates.finalize()
    uid_mapper.lookups = 0
    uid_mapper.minted = 0

    # -- pass 2: apply ------------------------------------------------------ #
    scrubber.discover = False
    results: list[FileResult] = []
    pending_writes: list[tuple[FileResult, bytes]] = []
    for root, p in targets:
        rel = p.relative_to(root).as_posix()
        res = FileResult(p, paths.root_labels[root], redact_rel_path(rel, scrubber), file_kind(p))
        scrubber.begin_file(str(p), _fallback_core(root, p))
        try:
            new_bytes = _dispatch(p, scrubber, res)
        except ScrubError as exc:
            res.error = str(exc)
            results.append(res)
            raise ScrubError(f"aborting: {exc}") from exc
        except Exception as exc:  # noqa: BLE001
            raise ScrubError(f"{p}: apply pass failed: {type(exc).__name__}: {exc}") from exc
        scrubber.end_file()
        if new_bytes is not None:
            res.changed = True
            pending_writes.append((res, new_bytes))
        results.append(res)

    # -- verify mode: no writing, just an assertion -------------------------- #
    exit_code = 0
    if args.verify:
        residual = sum(
            1 for r in results for f in r.findings if f.category in RESIDUAL_CATEGORIES
        )
        if residual:
            exit_code = 2
    elif args.apply:
        exit_code = _perform_writes(pending_writes, paths)
    else:
        for res, _ in pending_writes:
            res.changed = False  # dry run changes nothing on disk

    # -- outputs ------------------------------------------------------------ #
    map_rows = 0
    if not args.verify and uid_mapper.forward:
        map_rows = uid_mapper.write_map(paths.map_out)

    path_ids = scan_path_identifiers(targets, paths, scrubber)
    report = build_report(
        mode, paths, policy, key, results, uid_mapper, surrogates, map_rows, path_ids
    )
    paths.report_out.parent.mkdir(parents=True, exist_ok=True)
    paths.report_out.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print_summary(report, results, paths, mode)
    return exit_code


def _fallback_core(root: Path, p: Path) -> str:
    """Case key used when a file declares no patient identity of its own."""
    rel_parent = p.parent.relative_to(root).as_posix() or p.parent.name
    return "dir:" + rel_parent


def _dispatch(p: Path, scrubber: Scrubber, res: FileResult) -> bytes | None:
    if p.suffix.lower() == ".mrml":
        return scrub_mrml(p, scrubber, res)
    return scrub_nrrd(p, scrubber, res)


def _perform_writes(pending: list[tuple[FileResult, bytes]], paths: RunPaths) -> int:
    """Back up everything first, then write; abort before any write on conflict."""
    plan: list[tuple[FileResult, bytes, Path]] = []
    for res, data in pending:
        root = next(r for r in paths.roots if _is_within(res.path, r))
        backup = paths.backup_dir / paths.root_labels[root] / res.path.relative_to(root)
        if backup.exists():
            raise ScrubError(
                f"backup target already exists: {backup}\n"
                "Refusing to overwrite a previous backup - the original would become "
                "unrecoverable. Point --backup-dir at a fresh directory."
            )
        plan.append((res, data, backup))

    seen: set[Path] = set()
    for _res, _data, backup in plan:
        if backup in seen:
            raise ScrubError(f"two source files map to the same backup path: {backup}")
        seen.add(backup)

    paths.backup_dir.mkdir(parents=True, exist_ok=True)
    manifest = []
    for res, data, backup in plan:
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(res.path, backup)
        if backup.stat().st_size != res.path.stat().st_size:
            raise ScrubError(f"backup of {res.path} is truncated; aborting before any write")
        tmp = res.path.with_name(res.path.name + ".deid-tmp")
        try:
            tmp.write_bytes(data)
            os.replace(tmp, res.path)
        finally:
            if tmp.exists():
                tmp.unlink()
        res.backup_path = str(backup)
        manifest.append({"original": str(res.path), "backup": str(backup), "kind": res.kind})
    (paths.backup_dir / "MANIFEST.json").write_text(
        json.dumps({"tool": TOOL_NAME, "version": TOOL_VERSION, "entries": manifest}, indent=2),
        encoding="utf-8",
    )
    return 0


def build_report(
    mode: str,
    paths: RunPaths,
    policy: Policy,
    key: bytes,
    results: list[FileResult],
    uid_mapper: UidMapper,
    surrogates: SurrogateRegistry,
    map_rows: int,
    path_identifiers: list[dict[str, Any]],
) -> dict[str, Any]:
    by_cat: Counter[str] = Counter()
    by_kind: Counter[str] = Counter()
    files_with = 0
    residual = 0
    for r in results:
        by_kind[r.kind] += 1
        if r.findings:
            files_with += 1
        for f in r.findings:
            by_cat[f.category] += f.count if f.category == CAT_DICOM_UID else 1
            if f.category in RESIDUAL_CATEGORIES:
                residual += 1
    return {
        "tool": TOOL_NAME,
        "version": TOOL_VERSION,
        "mode": mode,
        "generated_utc": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        "key_fingerprint": key_fingerprint(key),
        "phi_ref_note": (
            "phi_ref is HMAC-SHA256(report_salt, value)[:12]; the report never contains a "
            "PHI value. Two findings with the same phi_ref removed the same string."
        ),
        "roots": [{"label": paths.root_labels[r], "path": str(r)} for r in paths.roots],
        "outputs": {
            "backup_dir": str(paths.backup_dir),
            "key_file": str(paths.key_file),
            "map_out": str(paths.map_out),
            "report": str(paths.report_out),
        },
        "policy": {
            "date_policy": policy.date_mode,
            "cyrillic_policy": policy.cyrillic_mode,
            "mrn_min_digits": policy.mrn_min_digits,
            "mrn_max_digits": policy.mrn_max_digits,
            "date_shift_window_days": policy.date_shift_window,
            "uid_generator": "MOS-DATA-032 2.25.<hmac-sha256 uuid int>",
            "well_known_uid_root_passthrough": DICOM_WELL_KNOWN_UID_ROOT,
        },
        "totals": {
            "files_scanned": len(results),
            "files_by_kind": dict(sorted(by_kind.items())),
            "files_with_findings": files_with,
            "files_written": sum(1 for r in results if r.changed and r.backup_path),
            "findings_total": sum(len(r.findings) for r in results),
            "findings_by_category": {c: by_cat.get(c, 0) for c in ALL_CATEGORIES if by_cat.get(c)},
            "residual_phi_findings": residual,
            "uid_lookups": uid_mapper.lookups,
            "uid_distinct_remapped": len(uid_mapper.forward),
            "uid_loaded_from_map": uid_mapper.loaded_rows,
            "uid_already_deidentified": len(uid_mapper.already_deidentified),
            "uid_wellknown_passthrough": len(uid_mapper.passthrough),
            "uid_map_rows_written": map_rows,
            "case_surrogates": surrogates.cases,
        },
        "verify": {
            "residual_categories": sorted(RESIDUAL_CATEGORIES),
            "residual_phi_findings": residual,
            "passed": residual == 0,
            "note": (
                "date and dicom_uid are excluded from the residual assertion: a shifted "
                "date and a remapped UID are indistinguishable in shape from the originals, "
                "so their presence is not evidence that a file was missed."
            ),
        },
        "residual_path_identifiers": {
            "note": (
                "Identifiers in file/directory NAMES. Not rewritten - Slicer fileName "
                "attributes and NRRD 'data file' fields reference these names, so renaming "
                "them here would break the scenes. Rename as a separate, coordinated step."
            ),
            "distinct_components": len(path_identifiers),
            "components": path_identifiers,
        },
        "files": [r.to_json() for r in results if r.findings or r.error],
    }


def print_summary(report: dict[str, Any], results: list[FileResult], paths: RunPaths, mode: str) -> None:
    t = report["totals"]
    line = "-" * 78
    print(line)
    print(f"{TOOL_NAME} {TOOL_VERSION}   mode={mode}   key={report['key_fingerprint']}")
    print(line)
    for r in report["roots"]:
        print(f"  root {r['label']:<28} {r['path']}")
    print(line)
    print(f"  {'files scanned':<34}{t['files_scanned']:>10}")
    for kind, n in t["files_by_kind"].items():
        print(f"    {kind:<32}{n:>10}")
    print(f"  {'files with findings':<34}{t['files_with_findings']:>10}")
    print(f"  {'files written':<34}{t['files_written']:>10}")
    print(line)
    print(f"  {'category':<34}{'count':>10}")
    print(f"  {'-' * 34}{'-' * 10:>10}")
    for cat in ALL_CATEGORIES:
        n = t["findings_by_category"].get(cat)
        if n:
            print(f"  {cat:<34}{n:>10}")
    print(f"  {'-' * 34}{'-' * 10:>10}")
    print(f"  {'findings total':<34}{t['findings_total']:>10}")
    print(f"  {'of which residual-PHI':<34}{t['residual_phi_findings']:>10}")
    print(line)
    print(f"  {'distinct UIDs in map':<34}{t['uid_distinct_remapped']:>10}")
    print(f"  {'UID lookups':<34}{t['uid_lookups']:>10}")
    print(f"  {'loaded from existing map':<34}{t['uid_loaded_from_map']:>10}")
    print(f"  {'already de-identified (skipped)':<34}{t['uid_already_deidentified']:>10}")
    print(f"  {'well-known UIDs passed through':<34}{t['uid_wellknown_passthrough']:>10}")
    print(f"  {'case surrogates allocated':<34}{t['case_surrogates']:>10}")
    print(line)
    rp = report["residual_path_identifiers"]
    if rp["distinct_components"]:
        cat_counts: Counter[str] = Counter()
        for comp in rp["components"]:
            for c in comp["categories"]:
                cat_counts[c] += 1
        print(f"  NOT REWRITTEN - identifiers in file/directory names: "
              f"{rp['distinct_components']} distinct components")
        for c, n in sorted(cat_counts.items()):
            print(f"    {c:<32}{n:>10}")
        print("    (renaming would break the fileName references inside the scenes)")
        print(line)

    worst = sorted((r for r in results if r.findings), key=lambda r: -len(r.findings))[:10]
    if worst:
        print("  top files by finding count (paths PHI-redacted):")
        for r in worst:
            cats = ",".join(sorted({f.category for f in r.findings}))
            print(f"    {len(r.findings):>6}  {r.root_label}/{r.rel_path}")
            print(f"            {cats}")
        print(line)
    print(f"  report : {paths.report_out}")
    if mode != "verify":
        print(f"  uid map: {paths.map_out}   (PHI-equivalent: contains source UIDs)")
        print(f"  key    : {paths.key_file}  (the ONLY way to re-identify)")
    if mode == "dry-run":
        print("  DRY RUN - nothing was written to the dataset. Re-run with --apply to write.")
    elif mode == "verify":
        residual = t["residual_phi_findings"]
        print(f"  VERIFY - residual PHI findings: {residual}")
        print(f"           (categories asserted on: {', '.join(sorted(RESIDUAL_CATEGORIES))})")
        print("  PASS" if residual == 0 else "  FAIL - exit code 2")
    print(line)


