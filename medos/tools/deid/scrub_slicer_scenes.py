def load_or_create_key(key_path: Path, *, allow_create: bool) -> bytes:
    """Return the 32-byte de-identification secret, creating it if permitted.

    The secret is the *only* way to reverse the mapping (MOS-DATA-032/035), so
    generating one silently would be a data-loss bug: the caller is shouted at.
    """
    if key_path.exists():
        raw = key_path.read_text(encoding="ascii").strip()
        try:
            key = bytes.fromhex(raw)
        except ValueError as exc:
            raise ScrubError(
                f"--key-file {key_path} does not contain hex.\n"
                f"Expected 64 hex characters (32 bytes). Parse error: {exc}"
            ) from exc
        if len(key) < 32:
            raise ScrubError(
                f"--key-file {key_path} holds only {len(key)} bytes; at least 32 are required. "
                "Delete it and re-run to mint a fresh key, but be aware that every UID "
                "already mapped under the old key becomes unreachable (MOS-DATA-032: key "
                "rotation is a breaking operation)."
            )
        return key

    if not allow_create:
        raise ScrubError(
            f"--key-file {key_path} does not exist and key creation is disabled in this mode.\n"
            "Run the dry run first (which mints the key) or pass an existing key file."
        )

    key = secrets.token_bytes(32)
    key_path.parent.mkdir(parents=True, exist_ok=True)
    key_path.write_text(key.hex(), encoding="ascii")
    try:
        os.chmod(key_path, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        # Windows ACLs do not map onto POSIX mode bits; the warning below stands.
        pass
    sys.stderr.write(
        "\n"
        "!!! ============================================================== !!!\n"
        "!!! A NEW DE-IDENTIFICATION SECRET WAS GENERATED                   !!!\n"
        "!!! ============================================================== !!!\n"
        f"!!!   {key_path}\n"
        "!!! This key is the ONLY way to re-identify anything this tool\n"
        "!!! pseudonymised.  Lose it and every UID mapping is permanently\n"
        "!!! unreachable; leak it and the pseudonymisation is void.\n"
        "!!! Store it OUTSIDE the dataset tree, in a secret store, backed up\n"
        "!!! separately from the data.  Do not commit it.\n"
        "!!! Re-running with a different key mints a DIFFERENT UID space and\n"
        "!!! orphans every result already produced (MOS-DATA-031/032).\n"
        "!!! ============================================================== !!!\n\n"
    )
    return key


def key_fingerprint(key: bytes) -> str:
    """Short public identifier for a key, so reports can be matched to a key file."""
    return hmac.new(key, b"medicalos/deid/key-fingerprint", hashlib.sha256).hexdigest()[:16]


# --------------------------------------------------------------------------- #
# UID mapping - MOS-DATA-032 verbatim, plus the MOS-DATA-033 collision guard.
# --------------------------------------------------------------------------- #
def deid_uid(tenant_deid_key: bytes, source_uid: str) -> str:
    """Deterministic, key-separated, collision-resistant UID surrogate.

    Reproduced from spec MOS-DATA-032 unchanged; output is the DICOM
    `2.25.<uuid-as-integer>` form, at most 44 characters.
    """
    digest = hmac.new(tenant_deid_key, source_uid.encode("ascii"), hashlib.sha256).digest()
    b = bytearray(digest[:16])
    b[6] = (b[6] & 0x0F) | 0x40  # UUID version 4
    b[8] = (b[8] & 0x3F) | 0x80  # RFC 4122 variant
    return "2.25." + str(uuid.UUID(bytes=bytes(b)).int)


class UidMapper:
    """Process-wide source-UID -> surrogate-UID map (MOS-DATA-031/033).

    One instance per run.  Holding it at run scope rather than per file is the
    whole point: the same source UID must come out identical in the scene that
    declares the series and in every scene that merely references it.
    """

    def __init__(self, key: bytes) -> None:
        self._key = key
        self.forward: dict[str, str] = {}
        self._reverse: dict[str, str] = {}
        self.kinds: dict[str, str] = {}
        self.passthrough: set[str] = set()
        self.already_deidentified: set[str] = set()
        self.loaded_rows = 0
        self.lookups = 0
        self.minted = 0

    def load_existing(self, path: Path) -> int:
        """Re-hydrate a previous run's map.

        MOS-DATA-033 makes the map record authoritative and MOS-DATA-032 merely
        the generator that rebuilds it.  Loading it here is what makes a second
        run over already-scrubbed data a no-op instead of a second remapping:
        without it, re-running would mint surrogates *of the surrogates* and
        orphan every reference produced by the first run.
        """
        if not path.exists():
            return 0
        rows = 0
        with path.open("r", encoding="utf-8") as fh:
            for lineno, line in enumerate(fh, 1):
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                except json.JSONDecodeError as exc:
                    raise ScrubError(f"{path}:{lineno}: UID map is not valid JSON Lines: {exc}") from exc
                if "_meta" in obj:
                    continue
                src, dst = obj.get("source_uid"), obj.get("mapped_uid")
                if not src or not dst:
                    raise ScrubError(f"{path}:{lineno}: UID map row missing source_uid/mapped_uid")
                expected = deid_uid(self._key, src)
                if expected != dst:
                    raise ScrubError(
                        f"{path}:{lineno}: UID map row was produced under a different key "
                        f"(ref {short_hash(src)}). Using it now would mix two UID spaces, "
                        "which MOS-DATA-032 forbids. Point --key-file at the matching key."
                    )
                self.forward[src] = dst
                self._reverse[dst] = src
                self.kinds[src] = obj.get("uid_kind", "other")
                rows += 1
        self.loaded_rows = rows
        return rows

    def map_uid(self, source_uid: str, kind: str = "other") -> str:
        """Map one UID, or return it unchanged if it is DICOM-registered."""
        self.lookups += 1
        if source_uid.startswith(DICOM_WELL_KNOWN_UID_ROOT):
            # MOS-DATA-034: SOP class / transfer syntax UIDs are not identifiers.
            self.passthrough.add(source_uid)
            return source_uid
        if source_uid in self._reverse:
            # This is a surrogate we already minted under this key. Leave it.
            self.already_deidentified.add(source_uid)
            return source_uid
        existing = self.forward.get(source_uid)
        if existing is not None:
            if kind != "other":
                self.kinds.setdefault(source_uid, kind)
            return existing
        mapped = deid_uid(self._key, source_uid)
        clash = self._reverse.get(mapped)
        if clash is not None and clash != source_uid:
            # MOS-DATA-033: abort rather than overwrite. A 128-bit HMAC collision
            # here means something is badly wrong, not that we should guess.
            raise ScrubError(
                "UID surrogate collision: two distinct source UIDs derived the same "
                f"surrogate {mapped}. Aborting (MOS-DATA-033). "
                f"refs: {short_hash(source_uid)} and {short_hash(clash)}"
            )
        self.forward[source_uid] = mapped
        self._reverse[mapped] = source_uid
        self.kinds[source_uid] = kind
        self.minted += 1
        return mapped

    def write_map(self, path: Path) -> int:
        """Persist the map as JSON Lines.

        The file holds *plaintext* source UIDs - it is the re-identification
        table (MOS-DATA-033 stores the same thing as AEAD ciphertext in the real
        platform) and must be handled as PHI-equivalent.  Callers are responsible
        for keeping it outside the dataset tree; `resolve_paths` enforces that.
        """
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(
                json.dumps(
                    {
                        "_meta": "medicalos deid_uid_map",
                        "generator": "MOS-DATA-032",
                        "key_fingerprint": key_fingerprint(self._key),
                        "rows": len(self.forward),
                        "warning": "CONTAINS SOURCE UIDS - treat as PHI-equivalent",
                    }
                )
                + "\n"
            )
            for src in sorted(self.forward):
                fh.write(
                    json.dumps(
                        {
                            "source_uid": src,
                            "mapped_uid": self.forward[src],
                            "uid_kind": self.kinds.get(src, "other"),
                        },
                        ensure_ascii=False,
                    )
                    + "\n"
                )
        try:
            os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
        except OSError:
            pass
        return len(self.forward)


