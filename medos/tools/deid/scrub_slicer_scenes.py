def short_hash(value: str, salt: bytes = b"medicalos/deid/unsalted") -> str:
    """Fallback reference used in error messages before the report salt exists."""
    return hashlib.sha256(salt + value.encode("utf-8")).hexdigest()[:12]


def normalise_identity(text: str) -> str:
    """Fold an identity string so trivial spelling variants share a surrogate.

    Case, accents and separator runs vary between the scene XML (`NAME 4923665
    MEDSI`) and the NRRD header (`Name_4923665_MEDSI`); folding them means the
    segment ID keeps referring to the same thing after scrubbing.
    """
    folded = unicodedata.normalize("NFKD", text)
    folded = "".join(ch for ch in folded if not unicodedata.combining(ch))
    folded = folded.casefold()
    folded = re.sub(r"[^0-9a-z\u0400-\u04FF]+", " ", folded)
    return " ".join(folded.split())


class SurrogateRegistry:
    """Stable `CASE_nnnn` tokens, derived from the secret so they survive reruns.

    Identities that co-occur in one value (a name next to its MRN) are unioned,
    so the PatientName attribute and the Segment0_ID string that embeds the same
    MRN collapse onto one token instead of two unrelated ones.
    """

    def __init__(self, key: bytes) -> None:
        self._key = key
        self._parent: dict[str, str] = {}
        self._canonical_rank: dict[str, int] = {}
        self._group_of: dict[str, str] = {}
        self._assigned: dict[str, str] = {}
        self.frozen = False

    # -- union-find over identity cores ------------------------------------ #
    def _find(self, item: str) -> str:
        self._parent.setdefault(item, item)
        root = item
        while self._parent[root] != root:
            root = self._parent[root]
        while self._parent[item] != root:
            self._parent[item], item = root, self._parent[item]
        return root

    def declare(self, core: str, rank: int) -> None:
        """Register an identity core.  Lower rank == better canonical choice."""
        if self.frozen:
            raise ScrubError(
                f"identity core appeared during the apply pass but not during discovery "
                f"(ref {short_hash(core)}). The two passes disagreed, which would emit "
                "inconsistent surrogates; aborting instead."
            )
        self._find(core)
        self._canonical_rank[core] = min(self._canonical_rank.get(core, rank), rank)

    def link(self, cores: Sequence[str]) -> None:
        """Union identity cores observed inside one value."""
        if len(cores) < 2:
            return
        root = self._find(cores[0])
        for other in cores[1:]:
            other_root = self._find(other)
            if other_root == root:
                continue
            # Deterministic merge direction: better rank wins, then lexical order.
            a = (self._canonical_rank.get(root, 99), root)
            b = (self._canonical_rank.get(other_root, 99), other_root)
            keep, drop = (root, other_root) if a <= b else (other_root, root)
            self._parent[drop] = keep
            root = keep

    def finalize(self) -> None:
        """Close discovery and allocate every `CASE_nnnn` token in one shot.

        Allocating here, in sorted group order rather than in file-visit order,
        is what makes the collision fallback reproducible: the token a case gets
        depends only on the key and the set of identities, never on which scene
        happened to be read first.
        """
        groups: dict[str, list[str]] = defaultdict(list)
        for core in self._parent:
            groups[self._find(core)].append(core)
        canonical: dict[str, str] = {}
        for root, members in groups.items():
            members.sort(key=lambda c: (self._canonical_rank.get(c, 99), c))
            canonical[root] = members[0]
        for core in self._parent:
            self._group_of[core] = canonical[self._find(core)]

        taken: dict[str, str] = {}
        for group in sorted(set(canonical.values())):
            digest = hmac.new(self._key, ("case:" + group).encode("utf-8"), hashlib.sha256).digest()
            base = f"CASE_{int.from_bytes(digest[:4], 'big') % 10000:04d}"
            token = base
            if token in taken:
                token = f"{base}_{digest[4:6].hex()}"
                if token in taken:
                    raise ScrubError(
                        f"surrogate collision for {token}; the CASE_ token space is too "
                        "small for this corpus (needs a code change, not a retry)."
                    )
            taken[token] = group
            self._assigned[group] = token
        self.frozen = True

    def surrogate(self, core: str) -> str:
        """Return the `CASE_nnnn` token for an identity core."""
        group = self._group_of.get(core)
        if group is None:
            raise ScrubError(
                f"identity core was never declared during discovery (ref {short_hash(core)}); "
                "refusing to mint an unregistered surrogate."
            )
        return self._assigned[group]

    def date_offset_days(self, core: str, window: int) -> int:
        """Per-case date shift, so intervals inside one case stay exact."""
        group = self._group_of.get(core, core)
        digest = hmac.new(self._key, ("dateshift:" + group).encode("utf-8"), hashlib.sha256).digest()
        span = 2 * window + 1
        return int.from_bytes(digest[:4], "big") % span - window

    @property
    def cases(self) -> int:
        return len(self._assigned)


