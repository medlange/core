@dataclass
class Finding:
    """One PHI removal or remap.  `phi_ref` stands in for the value, always."""

    location: str
    category: str
    action: str
    phi_ref: str
    count: int = 1
    surrogate: str | None = None

    def to_json(self) -> dict[str, Any]:
        out = {
            "location": self.location,
            "category": self.category,
            "action": self.action,
            "phi_ref": self.phi_ref,
            "count": self.count,
        }
        if self.surrogate is not None:
            out["surrogate"] = self.surrogate
        return out


@dataclass
class FileResult:
    path: Path
    root_label: str
    rel_path: str
    kind: str
    findings: list[Finding] = field(default_factory=list)
    uids_remapped: int = 0
    changed: bool = False
    backup_path: str | None = None
    error: str | None = None

    @property
    def attributes_changed(self) -> list[str]:
        return sorted({f.location for f in self.findings})

    def to_json(self) -> dict[str, Any]:
        # Count UIDs individually (one finding can cover a list of hundreds) so
        # these numbers add up to the run totals.
        by_cat: Counter[str] = Counter()
        for f in self.findings:
            by_cat[f.category] += f.count if f.category == CAT_DICOM_UID else 1
        return {
            "root": self.root_label,
            "path": self.rel_path,
            "kind": self.kind,
            "changed": self.changed,
            "backup": self.backup_path,
            "uids_remapped": self.uids_remapped,
            "findings_total": len(self.findings),
            "findings_by_category": dict(sorted(by_cat.items())),
            "attributes_changed": self.attributes_changed,
            "findings": [f.to_json() for f in self.findings],
            "error": self.error,
        }


# --------------------------------------------------------------------------- #
# The scrubber
# --------------------------------------------------------------------------- #
@dataclass
class Policy:
    mrn_min_digits: int
    mrn_max_digits: int
    date_mode: str  # shift | redact | keep
    date_shift_window: int
    cyrillic_mode: str  # redact | path-only | keep
    date_min_year: int
    date_max_year: int


class Scrubber:
    """Value-level PHI detection and replacement.

    Two passes over the corpus: `discover=True` only registers identity cores and
    their links, `discover=False` performs replacement.  The split exists so a
    name seen alone in file A gets the same token as the same name seen next to
    its MRN in file B.
    """

    def __init__(
        self,
        *,
        uid_mapper: UidMapper,
        surrogates: SurrogateRegistry,
        policy: Policy,
        report_salt: bytes,
    ) -> None:
        self.uids = uid_mapper
        self.surrogates = surrogates
        self.policy = policy
        self._salt = report_salt
        self.discover = True
        self.link_scope = "file"
        self._case_core: str | None = None  # identity core of the file being scrubbed
        self._file_fallback_core = "unknown"
        self._file_cores: list[str] = []
        self._pending_weak: list[str] = []
        self._file_case: dict[str, str] = {}  # file key -> canonical identity core
        self._file_key = ""

    # -- reporting helpers -------------------------------------------------- #
    def phi_ref(self, value: str) -> str:
        return hmac.new(self._salt, value.encode("utf-8"), hashlib.sha256).hexdigest()[:12]

    def begin_file(self, file_key: str, fallback_core: str) -> None:
        self._file_key = file_key
        self._file_fallback_core = fallback_core
        self._file_cores = []
        self._pending_weak = []
        # In the apply pass the case core is already known from discovery, so a
        # date encountered before the patient node still gets the case's offset.
        self._case_core = None if self.discover else self._file_case.get(file_key)

    def end_file(self) -> None:
        """Close a file: union its identities and remember its canonical core.

        One Slicer scene in these corpora describes one case, so a name found in
        the PatientName attribute and an MRN found in a model name belong to the
        same person even though they never appear in the same string.  With
        --link-scope element that assumption is dropped.

        Weak identities (free-form names, study IDs) are resolved only here,
        *after* the file's strong identifiers are known, and are namespaced by the
        file's case.  Namespacing them matters: an institution name or a StudyID
        of "1" is identical in every scene, and a globally-keyed weak core would
        transitively union every case in the corpus into a single surrogate.
        """
        if not self.discover:
            return
        strong = sorted(set(self._file_cores))
        if self.link_scope == "file" and len(strong) > 1:
            self.surrogates.link(strong)
        if self._case_core is None and strong:
            self._case_core = strong[0]

        case = self._case_core or self._file_fallback_core
        if self._case_core is None and self._pending_weak:
            # No strong identifier in this file: anchor its weak names to the
            # directory, so the scene still gets exactly one CASE_ token.
            self.surrogates.declare(case, 4)
        for norm in sorted(set(self._pending_weak)):
            core = f"name:{case}:{norm}"
            self.surrogates.declare(core, 3)
            self.surrogates.link([case, core])

        if self._case_core is not None or self._pending_weak:
            self._file_case[self._file_key] = case

    def _note_core(self, core: str) -> None:
        self._file_cores.append(core)

    def _weak_core(self, text: str) -> str:
        """Namespace a free-form identity by the file's case (see end_file)."""
        return f"name:{self._case_key()}:{normalise_identity(text)}"

    def _case_key(self) -> str:
        return self._case_core or self._file_fallback_core

    # -- identity cores ----------------------------------------------------- #
    def _identity_cores(self, text: str) -> list[tuple[str, str, int]]:
        """Return (core, category, rank) for every hard identity marker in `text`.

        Rank orders canonical choice: an MRN beats a pseudonym beats a name,
        because the MRN is the value most likely to recur verbatim elsewhere.
        """
        cores: list[tuple[str, str, int]] = []
        claimed: set[str] = set()
        for m in RE_PSEUDONYM.finditer(text):
            cores.append(("svr:" + m.group(0).upper().replace("-", "_"), CAT_PSEUDONYM, 1))
            claimed.update(re.findall(r"\d+", m.group(0)))
        for m in RE_UNNAMED.finditer(text):
            cores.append(("acc:" + m.group(1), CAT_ACCESSION, 2))
            claimed.add(m.group(1))
        for m in RE_DIGIT_RUN.finditer(text):
            digits = m.group(1)
            # `Unnamed - 10193927` is one identifier, not an accession plus an
            # MRN that happen to share digits; counting it twice inflates the
            # report and splits the surrogate across two cores.
            if digits in claimed:
                continue
            if not self._is_mrn(text, m.start(1), m.end(1), digits):
                continue
            cores.append(("mrn:" + digits, CAT_PATIENT_ID, 0))
        return cores

    def _is_mrn(self, text: str, start: int, end: int, digits: str) -> bool:
        """Reject digit runs that are codes or dates rather than record numbers."""
        if not (self.policy.mrn_min_digits <= len(digits) <= self.policy.mrn_max_digits):
            return False
        prev_ch = text[start - 1] if start > 0 else ""
        next_ch = text[end] if end < len(text) else ""
        # SCT^85756007^Tissue and (DCM,112031,...) are coding-scheme code values.
        # The membership test is against a tuple, not a string: `"" in "^,"` is
        # True, which silently exempted every value that was *exactly* a digit
        # run - which is precisely the shape of a bare patient ID.
        if prev_ch in CODE_DELIMITERS and next_ch in CODE_DELIMITERS:
            return False
        if self._looks_like_date(digits):
            return False
        return True

    def _looks_like_date(self, digits: str) -> bool:
        if len(digits) != 8:
            return False
        try:
            year = int(digits[:4])
            if not (self.policy.date_min_year <= year <= self.policy.date_max_year):
                return False
            _dt.date(year, int(digits[4:6]), int(digits[6:8]))
        except ValueError:
            return False
        return True

    # -- date handling ------------------------------------------------------ #
    def _shift_date(self, digits: str) -> str:
        offset = self.surrogates.date_offset_days(self._case_key(), self.policy.date_shift_window)
        try:
            d = _dt.date(int(digits[:4]), int(digits[4:6]), int(digits[6:8]))
        except ValueError as exc:
            raise ScrubError(f"unparseable DICOM DA value (ref {self.phi_ref(digits)}): {exc}") from exc
        return (d + _dt.timedelta(days=offset)).strftime("%Y%m%d")

    def _apply_date(self, digits: str, location: str, out: list[Finding]) -> str:
        if self.policy.date_mode == "keep":
            return digits
        if self.policy.date_mode == "redact":
            new = ""
        else:
            new = self._shift_date(digits)
        out.append(
            Finding(
                location=location,
                category=CAT_DATE,
                action="shift" if self.policy.date_mode == "shift" else "redact",
                phi_ref=self.phi_ref(digits),
                surrogate=new or None,
            )
        )
        return new

    # -- core value scrub --------------------------------------------------- #
    def scrub_value(self, location: str, key: str, value: str) -> tuple[str, list[Finding]]:
        """Scrub one XML attribute or NRRD header field value."""
        if not value or key in SKIP_ATTRS or RE_PURE_NUMERIC.match(value):
            return value, []
        if key == "SegmentationDisplayProperties":
            return self._scrub_segmentation_display(location, value)
        if RE_PATH_ATTR.match(key):
            return self._scrub_path(location, value)
        if key in COMPOSITE_ATTRS or "|" in value or "^" in value:
            return self._scrub_composite(location, value)
        return self._scrub_free(location, key, value)

    # -- composite `a^b|c^d|` / `a:b|c:d` ----------------------------------- #
    @staticmethod
    def _partition_item(item: str) -> tuple[str, str, str]:
        i_caret = item.find("^")
        i_colon = item.find(":")
        candidates = [i for i in (i_caret, i_colon) if i >= 0]
        if not candidates:
            return "", "", item
        i = min(candidates)
        return item[:i], item[i], item[i + 1 :]

    def _scrub_composite(self, location: str, value: str) -> tuple[str, list[Finding]]:
        findings: list[Finding] = []
        parts = value.split("|")
        for idx, item in enumerate(parts):
            if not item:
                continue
            key, sep, val = self._partition_item(item)
            where = f"{location}[{key}]" if key else location
            if key in BENIGN_ITEM_KEYS or not val:
                continue
            if key in UID_ITEM_KEYS:
                new_val, f = self._scrub_uid_list(where, val, kind=_uid_kind_for(key))
            elif key in DATE_ITEM_KEYS:
                new_val, f = self._scrub_date_value(where, val)
            elif key in SITE_ITEM_KEYS:
                new_val, f = self._scrub_site_value(where, val)
            elif key in IDENTITY_ITEM_KEYS:
                new_val, f = self._scrub_identity_value(where, val, IDENTITY_ITEM_KEYS[key])
            else:
                new_val, f = self._scrub_free(where, key, val)
            findings.extend(f)
            if new_val != val:
                parts[idx] = f"{key}{sep}{new_val}" if sep else new_val
        return ("|".join(parts), findings) if findings else (value, [])

    def _scrub_uid_list(self, location: str, value: str, kind: str) -> tuple[str, list[Finding]]:
        tokens = value.split()
        if not tokens:
            return value, []
        mapped_count = 0
        other_changed = False
        findings: list[Finding] = []
        out_tokens: list[str] = []
        for tok in tokens:
            if is_dicom_uid(tok):
                mapped = self.uids.map_uid(tok, kind)
                if mapped != tok:
                    mapped_count += 1
                out_tokens.append(tok if self.discover else mapped)
            else:
                # A `uids="DICOM^<value>"` entry is not always a UID: Slicer puts
                # the patient-level record number there. Dropping this branch's
                # result once left an MRN sitting in the scene.
                sub, sub_findings = self._scrub_free(location, "", tok)
                findings.extend(sub_findings)
                if sub != tok:
                    other_changed = True
                out_tokens.append(sub)
        if mapped_count:
            findings.append(
                Finding(
                    location=location,
                    category=CAT_DICOM_UID,
                    action="remap",
                    phi_ref=self.phi_ref(value if len(tokens) == 1 else f"<{len(tokens)} uids>"),
                    count=mapped_count,
                )
            )
        if self.discover or not (mapped_count or other_changed):
            return value, findings
        return " ".join(out_tokens), findings

    def _scrub_date_value(self, location: str, value: str) -> tuple[str, list[Finding]]:
        digits = value.strip()
        if not (len(digits) == 8 and digits.isdigit()):
            return self._scrub_free(location, "", value)
        findings: list[Finding] = []
        new = self._apply_date(digits, location, findings)
        return new, findings

    def _scrub_site_value(self, location: str, value: str) -> tuple[str, list[Finding]]:
        text = value.strip()
        if not text or text == SITE_SURROGATE or self.discover:
            return value, []
        return SITE_SURROGATE, [
            Finding(
                location=location,
                category=CAT_SITE_TOKEN,
                action="redact",
                phi_ref=self.phi_ref(text),
                surrogate=SITE_SURROGATE,
            )
        ]

    def _scrub_identity_value(self, location: str, value: str, category: str) -> tuple[str, list[Finding]]:
        text = value.strip()
        if not text or RE_NEUTRAL_TOKEN.match(text):
            # Already one of our own tokens: re-pseudonymising it would mint a
            # second surrogate for the same case and break every prior reference.
            return value, []
        cores = self._identity_cores(text)
        if self.discover:
            if cores:
                for c, _cat, r in cores:
                    self.surrogates.declare(c, r)
                    self._note_core(c)
                self.surrogates.link([c for c, _c, _r in cores])
                best = min(cores, key=lambda c: (c[2], c[0]))
                if best[2] <= 1 and self._case_core is None:
                    self._case_core = best[0]
            else:
                # Resolved in end_file(), once the file's strong cores are known.
                self._pending_weak.append(normalise_identity(text))
            return value, []
        core = min(cores, key=lambda c: (c[2], c[0]))[0] if cores else self._weak_core(text)
        token = self.surrogates.surrogate(core)
        return token, [
            Finding(
                location=location,
                category=category,
                action="pseudonymise",
                phi_ref=self.phi_ref(text),
                surrogate=token,
            )
        ]

    # -- SegmentationDisplayProperties: `<encodedSegmentID> Key:val ...|` ---- #
    def _scrub_segmentation_display(self, location: str, value: str) -> tuple[str, list[Finding]]:
        findings: list[Finding] = []
        records = value.split("|")
        for idx, rec in enumerate(records):
            if not rec.strip():
                continue
            head, sep, tail = rec.partition(" ")
            new_head, f = self._scrub_encoded_token(f"{location}[segmentID]", head)
            findings.extend(f)
            if new_head != head:
                records[idx] = new_head + sep + tail
        return ("|".join(records), findings) if findings else (value, [])

    # -- percent-encoded single token --------------------------------------- #
    def _scrub_encoded_token(self, location: str, token: str) -> tuple[str, list[Finding]]:
        """Scrub a token that may be percent-encoded, re-encoding only if changed."""
        if RE_PERCENT_ESCAPE.search(token):
            decoded = urllib.parse.unquote(token)
            new_decoded, findings = self._scrub_free(location, "", decoded)
            if new_decoded == decoded:
                return token, findings
            return urllib.parse.quote(new_decoded, safe=""), findings
        return self._scrub_free(location, "", token)

    # -- paths -------------------------------------------------------------- #
    def _scrub_path(self, location: str, value: str) -> tuple[str, list[Finding]]:
        """Reduce a path to its basename and scrub the basename in turn.

        A Slicer `fileName` is resolved relative to the scene, so a path that
        pointed into the annotator's home directory was already broken for anyone
        else; keeping only the basename loses nothing and removes the directory
        chain, which is where the names, MRNs and institution folders live.
        """
        raw = value
        encoded = bool(RE_PERCENT_ESCAPE.search(raw))
        decoded = urllib.parse.unquote(raw) if encoded else raw
        findings: list[Finding] = []

        has_dir = ("/" in decoded) or ("\\" in decoded)
        basename = re.split(r"[\\/]", decoded)[-1]
        directories = decoded[: len(decoded) - len(basename)]

        if has_dir:
            # Report what was in the directory chain by category rather than
            # lumping it all under "a path was shortened": the operator needs to
            # know an institution token or an MRN was sitting in a folder name.
            dir_cats: list[str] = []
            if RE_USER_HOME.search(directories):
                dir_cats.append(CAT_LOCAL_USER_PATH)
            if RE_CYRILLIC_RUN.search(directories) and self.policy.cyrillic_mode != "keep":
                dir_cats.append(CAT_CYRILLIC_TEXT)
            if RE_SITE_TOKEN.search(directories):
                dir_cats.append(CAT_SITE_TOKEN)
            if RE_UNNAMED.search(directories):
                dir_cats.append(CAT_ACCESSION)
            for _core, cat, _rank in self._identity_cores(directories):
                dir_cats.append(cat)
            if not dir_cats:
                dir_cats.append(CAT_FILESYSTEM_PATH)
            for cat in sorted(set(dir_cats)):
                findings.append(
                    Finding(
                        location=location,
                        category=cat,
                        action="drop_directories",
                        phi_ref=self.phi_ref(decoded),
                    )
                )

        new_base, base_findings = self._scrub_free(location, "", basename)
        findings.extend(base_findings)

        if self.discover:
            return value, []
        if not findings:
            return value, []
        if not has_dir and new_base == basename:
            return value, findings
        return (urllib.parse.quote(new_base, safe="") if encoded else new_base), findings

    # -- free text ---------------------------------------------------------- #
    def _scrub_free(self, location: str, key: str, value: str) -> tuple[str, list[Finding]]:
        """Scrub an unstructured value: markers, UIDs, dates, paths."""
        text = value
        if not text.strip():
            return value, []

        # A value that is itself a path gets path treatment even if its attribute
        # name did not say so (fileListMemberN is covered, but Slicer invents new
        # path-bearing attribute names between versions).
        if RE_PATH_LIKE.search(text) and len(text.split()) == 1 and key != "":
            return self._scrub_path(location, text)

        findings: list[Finding] = []

        # 0. A home-directory path can hide inside a free-form value that is not
        #    itself a path - Slicer stores `ScreenshotDirectory /Users/<login>/...`
        #    as one ScriptedModule parameter, which no path-attribute rule sees.
        if RE_USER_HOME.search(text):
            if not self.discover:
                text = RE_USER_HOME.sub(
                    lambda m: f"{m.group(1)}{m.group(2)}{m.group(1)}{USER_SURROGATE}", text
                )
                findings.append(
                    Finding(
                        location=location,
                        category=CAT_LOCAL_USER_PATH,
                        action="redact",
                        phi_ref=self.phi_ref(value),
                        surrogate=USER_SURROGATE,
                    )
                )

        # 1. Hard identity markers -> the whole value becomes one token.
        cores = self._identity_cores(text)
        site_hit = RE_SITE_TOKEN.search(text)
        cyr_hit = RE_CYRILLIC_RUN.search(text) if self.policy.cyrillic_mode == "redact" else None

        if cores:
            core = min(cores, key=lambda c: (c[2], c[0]))[0]
            if self.discover:
                for c, _cat, r in cores:
                    self.surrogates.declare(c, r)
                    self._note_core(c)
                self.surrogates.link([c for c, _cat, _r in cores])
                best_rank = min(c[2] for c in cores)
                if best_rank <= 1 and self._case_core is None:
                    self._case_core = core
                return value, []
            token = self.surrogates.surrogate(core)
            seen: set[str] = set()
            for _c, cat, _r in cores:
                if cat not in seen:
                    seen.add(cat)
                    findings.append(
                        Finding(
                            location=location,
                            category=cat,
                            action="pseudonymise",
                            phi_ref=self.phi_ref(text),
                            surrogate=token,
                        )
                    )
            if site_hit:
                findings.append(
                    Finding(
                        location=location,
                        category=CAT_SITE_TOKEN,
                        action="pseudonymise",
                        phi_ref=self.phi_ref(site_hit.group(0)),
                        surrogate=token,
                    )
                )
            if _has_name_words(text):
                findings.append(
                    Finding(
                        location=location,
                        category=CAT_PATIENT_NAME,
                        action="pseudonymise",
                        phi_ref=self.phi_ref(text),
                        surrogate=token,
                    )
                )
            ext_match = RE_FILE_EXT.search(text)
            return (token + ext_match.group(1) if ext_match else token), findings

        # 2. Site token or Cyrillic run without an identity core: still PHI, but
        #    there is no identity to anchor a CASE_ token to, so redact in place.
        if site_hit or cyr_hit:
            if self.discover:
                return value, []
            new = RE_SITE_TOKEN.sub("SITE_X", text)
            cat = CAT_SITE_TOKEN if site_hit else CAT_CYRILLIC_TEXT
            if cyr_hit:
                new = RE_CYRILLIC_RUN.sub("TEXT_REDACTED", new)
            findings.append(
                Finding(
                    location=location,
                    category=cat,
                    action="redact",
                    phi_ref=self.phi_ref(text),
                )
            )
            text = new

        # 3. Remap any DICOM UID appearing in free text.
        uid_count = 0

        def _uid_sub(m: re.Match[str]) -> str:
            nonlocal uid_count
            src = m.group(1)
            if not is_dicom_uid(src):
                return src
            mapped = self.uids.map_uid(src, "other")
            if mapped != src:
                uid_count += 1
            return mapped

        text2 = RE_UID.sub(_uid_sub, text)
        if uid_count and not self.discover:
            findings.append(
                Finding(
                    location=location,
                    category=CAT_DICOM_UID,
                    action="remap",
                    phi_ref=self.phi_ref("<free-text uids>"),
                    count=uid_count,
                )
            )
        text = text2

        # 4. Dates embedded in free text (e.g. "CT chest (20231030)").
        if self.policy.date_mode != "keep":
            date_findings: list[Finding] = []

            def _date_sub(m: re.Match[str]) -> str:
                digits = m.group(1)
                if not self._looks_like_date(digits):
                    return digits
                return self._apply_date(digits, location, date_findings)

            text = RE_DIGIT_RUN.sub(_date_sub, text)
            findings.extend(date_findings)

        if self.discover:
            return value, []
        return (text, findings) if findings else (value, [])


def _uid_kind_for(key: str) -> str:
    if key.endswith("StudyInstanceUID"):
        return "study"
    if key.endswith("SeriesInstanceUID"):
        return "series"
    if key.endswith("SOPInstanceUID") or key in ("DICOMInstanceUID", "DICOM.instanceUIDs"):
        return "sop"
    if key.endswith("FrameOfReferenceUID"):
        return "frame_of_reference"
    return "other"


def _has_name_words(text: str) -> bool:
    """True if the value carries capitalised word runs beside its marker."""
    words = re.split(r"[\s_]+", text)
    return sum(1 for w in words if RE_NAME_WORD.match(w)) >= 2


