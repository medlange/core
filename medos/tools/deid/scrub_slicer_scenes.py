# MRML handling
# --------------------------------------------------------------------------- #
def iter_elements(root: ET.Element) -> Iterator[ET.Element]:
    yield root
    for child in root:
        yield from iter_elements(child)


def scrub_mrml(path: Path, scrubber: Scrubber, result: FileResult) -> bytes | None:
    """Parse, scrub and re-serialise one .mrml scene.

    ElementTree is used rather than a regex because a MRML attribute value can
    contain `>` and quoted text, and because attribute *names* vary between
    Slicer versions - we must be able to sweep every attribute of every node, not
    a fixed list.
    """
    try:
        tree = ET.parse(path)
    except ET.ParseError as exc:
        raise ScrubError(f"{path}: not well-formed XML: {exc}") from exc
    root = tree.getroot()

    changed = False
    for el in iter_elements(root):
        for attr_name in list(el.attrib):
            old = el.attrib[attr_name]
            new, findings = scrubber.scrub_value(f"<{el.tag}>@{attr_name}", attr_name, old)
            if findings:
                result.findings.extend(findings)
                result.uids_remapped += sum(f.count for f in findings if f.category == CAT_DICOM_UID)
            if new != old and not scrubber.discover:
                el.attrib[attr_name] = new
                changed = True

    if scrubber.discover or not changed:
        return None

    buf = io.BytesIO()
    # short_empty_elements=False keeps Slicer's `<Tag ...></Tag>` form, so the
    # diff against the original is limited to the values we actually changed.
    tree.write(buf, encoding="UTF-8", xml_declaration=True, short_empty_elements=False)
    data = buf.getvalue()

    # Fail closed: prove the result still parses and still has the same shape.
    try:
        verify_root = ET.fromstring(data)
    except ET.ParseError as exc:
        raise ScrubError(f"{path}: scrubbed XML no longer parses: {exc}") from exc
    if len(list(iter_elements(verify_root))) != len(list(iter_elements(root))):
        raise ScrubError(f"{path}: element count changed during rewrite; refusing to write")
    return data


# --------------------------------------------------------------------------- #
# NRRD handling
# --------------------------------------------------------------------------- #
NRRD_FIELD_RE = re.compile(r"^([^:]+):(=|\s)(.*)$", re.DOTALL)


NRRD_HEADER_READ_CHUNK = 1 << 16
NRRD_HEADER_MAX_BYTES = 8 << 20


def read_nrrd_header(path: Path) -> tuple[bytes, int]:
    """Read only the NRRD header, stopping at the blank line that ends it.

    Reading the whole file here would mean pulling a 290 MB CT volume into memory
    to inspect 3 KB of text, twice (discovery and apply). The header is plain
    ASCII/UTF-8 terminated by a blank line; everything after it is opaque -
    possibly gzip, possibly raw - and is never read unless the file is actually
    rewritten.

    Returns (header_bytes, offset_of_blank_line).
    """
    buf = bytearray()
    with path.open("rb") as fh:
        while True:
            chunk = fh.read(NRRD_HEADER_READ_CHUNK)
            if not chunk:
                raise ScrubError(
                    f"{path}: reached end of file without a blank line terminating the "
                    "NRRD header; refusing to guess where the data starts."
                )
            buf += chunk
            sep = buf.find(b"\n\n")
            if sep >= 0:
                return bytes(buf[:sep]), sep
            if len(buf) > NRRD_HEADER_MAX_BYTES:
                raise ScrubError(
                    f"{path}: no blank line in the first {NRRD_HEADER_MAX_BYTES} bytes; "
                    "this does not look like a NRRD file."
                )


def read_nrrd_data(path: Path, offset: int) -> bytes:
    """Return the data segment verbatim, starting at the header's blank line.

    Never decoded, never re-encoded: the bytes handed back here are written out
    unchanged, which is what guarantees the voxels survive a header rewrite.
    """
    with path.open("rb") as fh:
        fh.seek(offset)
        return fh.read()


def parse_nrrd_header_lines(header: bytes) -> list[tuple[str, str, str, str]]:
    """Return (raw_line, key, separator, value) per header line."""
    out: list[tuple[str, str, str, str]] = []
    for raw in header.decode("utf-8", errors="strict").split("\n"):
        if not raw or raw.startswith("#") or raw.startswith("NRRD"):
            out.append((raw, "", "", ""))
            continue
        m = NRRD_FIELD_RE.match(raw)
        if not m:
            out.append((raw, "", "", ""))
            continue
        key, sep, value = m.group(1), m.group(2), m.group(3)
        if sep == " ":
            # `key: value` - the space is part of the separator, not the value.
            out.append((raw, key, ": ", value))
        else:
            out.append((raw, key, ":=", value))
    return out


def _header_fields_equal(a: Any, b: Any) -> bool:
    if isinstance(a, np.ndarray) or isinstance(b, np.ndarray):
        try:
            return bool(np.array_equal(np.asarray(a), np.asarray(b), equal_nan=True))
        except TypeError:
            return bool(np.array_equal(np.asarray(a), np.asarray(b)))
    if isinstance(a, (list, tuple)) and isinstance(b, (list, tuple)):
        return len(a) == len(b) and all(_header_fields_equal(x, y) for x, y in zip(a, b))
    return bool(a == b)


def scrub_nrrd(path: Path, scrubber: Scrubber, result: FileResult) -> bytes | None:
    """Rewrite only PHI-bearing NRRD *header* fields, byte-preserving the data."""
    header, data_offset = read_nrrd_header(path)
    try:
        lines = parse_nrrd_header_lines(header)
    except UnicodeDecodeError as exc:
        raise ScrubError(f"{path}: NRRD header is not valid UTF-8: {exc}") from exc

    changed = False
    new_lines: list[str] = []
    for raw, key, sep, value in lines:
        if not key or key in NRRD_STRUCTURAL_FIELDS or not value:
            new_lines.append(raw)
            continue
        new_value, findings = scrubber.scrub_value(f"nrrd:{key}", key, value)
        if findings:
            result.findings.extend(findings)
            result.uids_remapped += sum(f.count for f in findings if f.category == CAT_DICOM_UID)
        if new_value != value and not scrubber.discover:
            new_lines.append(f"{key}{sep}{new_value}")
            changed = True
        else:
            new_lines.append(raw)

    if scrubber.discover or not changed:
        return None

    new_header = "\n".join(new_lines).encode("utf-8")

    # Prove the rewrite: every field except the ones we touched must come back
    # byte-identical through pynrrd's own parser, and the data bytes are the
    # *original* object, never re-serialised.
    old_parsed = nrrd.read_header(io.BytesIO(header + b"\n\n"))
    new_parsed = nrrd.read_header(io.BytesIO(new_header + b"\n\n"))
    touched = {f.location.split(":", 1)[1].split("[")[0] for f in result.findings if f.location.startswith("nrrd:")}
    if set(old_parsed) != set(new_parsed):
        raise ScrubError(
            f"{path}: NRRD header field set changed during rewrite "
            f"({sorted(set(old_parsed) ^ set(new_parsed))}); refusing to write."
        )
    for fld in old_parsed:
        if fld in touched:
            continue
        if not _header_fields_equal(old_parsed[fld], new_parsed[fld]):
            raise ScrubError(
                f"{path}: NRRD header field {fld!r} changed during rewrite but was not a "
                "PHI target; refusing to write."
            )
    return new_header + read_nrrd_data(path, data_offset)


